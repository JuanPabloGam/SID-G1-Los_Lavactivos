/* ---------------------------------------------------------------------------
   10. VALIDACION Y CONFIRMACION (UNICO COMMIT DEL SCRIPT)
   Comprueba el numero de filas de cada tabla y las reglas de negocio de los
   datos cargados. Si todo es correcto ejecuta COMMIT y muestra el mensaje de
   exito. Si algo falla, ejecuta ROLLBACK y termina con ORA-20001 indicando
   que comprobacion fallo. No se confirma nada en ese caso.
   --------------------------------------------------------------------------- */
DECLARE
    v_n       NUMBER;
    v_fallos  VARCHAR2(3000);
    PROCEDURE verificar (p_descripcion IN VARCHAR2,
                         p_real        IN NUMBER,
                         p_esperado    IN NUMBER) IS
    BEGIN
        IF p_real <> p_esperado THEN
            v_fallos := v_fallos || CHR(10) || ' - ' || p_descripcion
                        || ': esperado ' || p_esperado || ', obtenido ' || p_real;
        END IF;
    END verificar;
BEGIN
    -- Filas cargadas por tabla
    SELECT COUNT(*) INTO v_n FROM EMPRESA;
    verificar('Filas en EMPRESA', v_n, 2);
    SELECT COUNT(*) INTO v_n FROM CLIENTE;
    verificar('Filas en CLIENTE', v_n, 15);
    SELECT COUNT(*) INTO v_n FROM EMPLEADO;
    verificar('Filas en EMPLEADO', v_n, 8);
    SELECT COUNT(*) INTO v_n FROM SERVICIO;
    verificar('Filas en SERVICIO', v_n, 12);
    SELECT COUNT(*) INTO v_n FROM VEHICULO;
    verificar('Filas en VEHICULO', v_n, 20);
    SELECT COUNT(*) INTO v_n FROM ORDEN_LAVADO;
    verificar('Filas en ORDEN_LAVADO', v_n, 20);
    SELECT COUNT(*) INTO v_n FROM DETALLE_ORDEN;
    verificar('Filas en DETALLE_ORDEN', v_n, 40);
    SELECT COUNT(*) INTO v_n FROM FACTURA;
    verificar('Filas en FACTURA', v_n, 20);
    SELECT COUNT(*) INTO v_n FROM PAGO;
    verificar('Filas en PAGO', v_n, 18);
    -- Reglas de negocio (cada comprobacion debe encontrar 0 casos con error)
    SELECT COUNT(*) INTO v_n
    FROM FACTURA F
    WHERE F.SUBTOTAL <> (SELECT NVL(SUM(D.PRECIO_APLICADO), 0)
                         FROM DETALLE_ORDEN D
                         WHERE D.ID_ORDEN = F.ID_ORDEN);
    verificar('Facturas con subtotal distinto de la suma de sus detalles', v_n, 0);
    SELECT COUNT(*) INTO v_n
    FROM FACTURA F
    WHERE F.IMPUESTOS <> ROUND(F.SUBTOTAL * 0.19, 2);
    verificar('Facturas con impuestos distintos del 19 por ciento', v_n, 0);
    SELECT COUNT(*) INTO v_n
    FROM (SELECT F.ID_FACTURA, F.ESTADO, F.TOTAL, NVL(SUM(P.MONTO), 0) AS PAGADO
          FROM FACTURA F
          LEFT JOIN PAGO P ON P.ID_FACTURA = F.ID_FACTURA
          GROUP BY F.ID_FACTURA, F.ESTADO, F.TOTAL) X
    WHERE X.PAGADO > X.TOTAL
       OR (X.ESTADO = 'PAGADA'  AND X.PAGADO <> X.TOTAL)
       OR (X.ESTADO = 'PARCIAL' AND (X.PAGADO <= 0 OR X.PAGADO >= X.TOTAL))
       OR (X.ESTADO = 'EMITIDA' AND X.PAGADO <> 0);
    verificar('Facturas con estado incoherente con sus pagos o pagos excedidos', v_n, 0);
    SELECT COUNT(*) INTO v_n
    FROM PAGO P
    JOIN FACTURA F ON F.ID_FACTURA = P.ID_FACTURA
    WHERE P.FECHA_PAGO < F.FECHA_EMISION;
    verificar('Pagos anteriores a la emision de su factura', v_n, 0);
    SELECT COUNT(*) INTO v_n
    FROM FACTURA F
    JOIN ORDEN_LAVADO O ON O.ID_ORDEN = F.ID_ORDEN
    WHERE F.FECHA_EMISION < O.FECHA_HORA_SALIDA;
    verificar('Facturas emitidas antes de la salida de su orden', v_n, 0);
    SELECT COUNT(*) INTO v_n
    FROM DETALLE_ORDEN D
    JOIN SERVICIO S ON S.ID_SERVICIO = D.ID_SERVICIO
    WHERE D.PRECIO_APLICADO <> S.PRECIO_BASE
       OR D.DETALLE <> S.NOMBRE_SERVICIO;
    verificar('Detalles que no coinciden con el catalogo de servicios', v_n, 0);
    SELECT COUNT(*) INTO v_n
    FROM ORDEN_LAVADO O
    JOIN EMPLEADO E ON E.ID_EMPLEADO = O.ID_EMPLEADO_ASIGNADO
    WHERE UPPER(E.CARGO) LIKE 'CAJER%';
    verificar('Ordenes asignadas a cajeros', v_n, 0);
    SELECT MAX(ID_PAGO) INTO v_n FROM PAGO;
    verificar('Mayor ID_PAGO cargado (SEQ_PAGO inicia en 19)', v_n, 18);
    IF v_fallos IS NULL THEN
        COMMIT;
        DBMS_OUTPUT.PUT_LINE('CARGA EXITOSA: 155 registros confirmados (COMMIT).');
